export function consoleProblem(code: string, copy: ProcessConsoleCopy): string {
  if (
    code === "authority_lost" ||
    ["identity_forbidden", "identity_unauthorized"].includes(code)
  )
    return copy.authority;
  if (code === "recovery_storage_invalid") return copy.storageInvalid;
  if (code === "recovery_storage_unavailable") return copy.storage;
  if (code === "connection_lost") return copy.connection;
  if (code === "response_invalid") return copy.response;
  if (code === "process_test_superseded") return copy.superseded;
  if (code === "process_qualification_required")
    return copy.qualificationMissing;
  if (code === "process_activation_version_changed") return copy.draftMismatch;
  if (
    code === "process_qualification_stale" ||
    code === "process_qualification_authority_changed"
  )
    return copy.sourceChanged;
  if (/budget|pricing/.test(code)) return copy.budget;
  if (/sources|source_changed/.test(code)) return copy.sourceChanged;
  if (/busy/.test(code)) return copy.busy;
  if (/conflict|snapshot|revision/.test(code)) return copy.conflict;
  return copy.unavailable;
}
