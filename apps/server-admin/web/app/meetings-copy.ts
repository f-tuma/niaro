export const meetingsCopy = { en, cs };
export function useMeetingsCopy(): MeetingsCopy {
  return meetingsCopy[useApp().language];
}

/** A failure code as copy: this page's own, the shared catalog's, or generic. */
export function meetingErrorText(
  code: string | null | undefined,
  copy: MeetingsCopy,
  language: "en" | "cs",
) {
  if (!code) return "";
  const own = copy[code as keyof MeetingsCopy];
  if (code.startsWith("meeting_") && typeof own === "string") return own;
  const tr = translate(language);
  return code in shared
    ? tr(code as keyof typeof shared)
    : tr("meeting_processing_failed");
}
