export function loopFieldValue(label: string, value: string, copy: LoopsCopy) {
  const known: Record<string, keyof LoopsCopy> = {
    composed: "composed",
    asked: "asked",
    answered: "answered",
    resolved: "resolved",
    clarification: "clarification",
    candidate: "candidate",
    active: "active",
    superseded: "superseded",
    deleted: "deleted",
    read: "read",
    write: "write",
    unconfirmed_failure: "unconfirmedOutcomeHint",
  };
  const key =
    ["Status", "Receipt status", "Effect", "Outcome"].includes(label) &&
    known[value];
  return key ? copy[key] : value;
}
/**
 * Decision steps record the option id the verifier chose ("service_0",
 * "matches"). Show what it means; a recorded criterion such as
 * "Acme CRM: …" names the picked service or action directly.
 */
export function loopDecisionChoiceLabel(
  choice: string,
  copy: LoopsCopy,
  criterion?: string,
) {
  const picked = /^(service|action)_\d+$/.exec(choice);
  if (picked) {
    const name = criterion?.split(": ")[0]?.trim();
    return name && name !== choice
      ? name
      : copy[picked[1] === "service" ? "choiceService" : "choiceAction"];
  }
  const known: Record<string, keyof LoopsCopy> = {
    fallback: "choiceNone",
    matches: "choiceMatches",
    mismatch: "choiceMismatch",
    complete: "choiceComplete",
    incomplete: "incomplete",
    continue_work: "choiceContinue",
    new_task: "choiceNewTask",
  };
  const key = known[choice];
  return key ? copy[key] : undefined;
}
export function loopDetailLabel(value: string, copy: LoopsCopy) {
  const key = detailLabels[value];
  return key ? copy[key] : value;
}
export function loopNodeLabel(
  node: { kind: string; label: string },
  copy: LoopsCopy,
) {
  if (node.kind === "tool") {
    const tools: Record<string, keyof LoopsCopy> = {
      find_service: "findService",
      use_actions: "useActions",
      find_actions: "findActions",
      compose_card: "composeCard",
      internal_datetime_resolve: "resolveDate",
      ask_user: "askUser",
      skill_load: "loadSkill",
      skill_propose: "proposeSkill",
      "Skill (@)": "mentionedSkill",
    };
    const purpose = tools[node.label];
    if (purpose) return copy[purpose];
  }
  if (node.kind === "model") {
    const numbered = node.label.match(/^Model (\d+)$/);
    if (numbered) return `${copy.model} ${numbered[1]}`;
    if (node.label === "Model tool request") return copy.modelToolRequest;
  }
  const labels: Record<string, keyof LoopsCopy> = {
    "Mastra model": "model",
    "Unknown tool": "unknownTool",
    Request: "request",
    "User request": "request",
    "Tool result": "result",
    "Decision / verification": "decision",
    "Waiting for the person": "waiting",
    Reply: "reply",
    "Assistant reply": "reply",
    "Run outcome": "outcome",
    "Unconfirmed outcome": "unconfirmedOutcome",
  };
  const key = node.kind !== "tool" && labels[node.label];
  return key ? copy[key] : node.label;
}
