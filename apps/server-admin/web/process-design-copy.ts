export function designProblem(code: string, copy: DesignCopy): string {
  if (code === "authority_lost") return copy.authorityLost;
  if (code === "connection_lost") return copy.connectionLost;
  if (code === "response_invalid") return copy.responseInvalid;
  if (code === "recovery_storage_unavailable") return copy.storage;
  if (code === "recovery_storage_invalid") return copy.storageInvalid;
  if (/interrupted|restarted/.test(code)) return copy.interruptedError;
  if (code === "process_design_model_changed") return copy.modelUnavailable;
  if (code.includes("busy")) return copy.busy;
  if (code === "catalog_budget_usage_unknown") return copy.budgetUnknown;
  if (code === "catalog_provider_limit") return copy.providerLimit;
  if (/budget_(exhausted|overrun)/.test(code)) return copy.budgetSpent;
  if (code === "process_design_model_failed") return copy.modelFailed;
  if (/budget|pricing|price/.test(code)) return copy.budget;
  if (/conflict|changed/.test(code)) return copy.conflict;
  if (/invalid|http_400/.test(code)) return copy.invalid;
  return copy.unavailableError;
}
